#!/usr/bin/env python3
"""Generate CMake mirror-unit metadata from closure manifests.

The rehearsal export can add units without requiring a hand-maintained source
list.  Only files present under mirror/ are emitted as build sources; external
provider inputs remain receipt metadata until their Vellum provider is wired.
"""
from __future__ import annotations

import json
import pathlib
import sys


SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".m", ".mm"}


def cmake_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 4:
        raise SystemExit("usage: generate_mirror_units.py MIRROR_ROOT CLOSURE_DIR OUTPUT")
    mirror_root = pathlib.Path(sys.argv[1]).resolve()
    closure_dir = pathlib.Path(sys.argv[2]).resolve()
    output = pathlib.Path(sys.argv[3])
    rows = []
    for manifest_path in sorted(closure_dir.glob("*.json")):
        data = json.loads(manifest_path.read_text())
        unit = manifest_path.stem
        targets = []
        for target in data.get("targets", []):
            sources = []
            for source in target.get("sources", []):
                source_path = pathlib.Path(source)
                if source_path.is_absolute():
                    continue
                candidate = mirror_root / source_path
                if candidate.exists() and candidate.suffix in SOURCE_SUFFIXES:
                    sources.append(candidate.relative_to(mirror_root.parent).as_posix())
            targets.append((target.get("name", ""), sources))
        rows.append((unit, targets))

    lines = ["# GENERATED by tools/packaging/generate_mirror_units.py; do not edit."]
    lines.append("set(VELLUM_MIRROR_UNITS")
    lines.extend(f"  {cmake_quote(unit)}" for unit, _ in rows)
    lines.append(")")
    for unit, targets in rows:
        key = unit.upper().replace("-", "_")
        lines.append(f"set(VELLUM_MIRROR_UNIT_{key}_TARGETS)")
        for target, sources in targets:
            safe = target.upper().replace("-", "_")
            lines.append(f"list(APPEND VELLUM_MIRROR_UNIT_{key}_TARGETS {cmake_quote(target)})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{safe}_SOURCES")
            lines.extend(f"  {cmake_quote(source)}" for source in sources)
            lines.append(")")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
