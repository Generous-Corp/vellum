#!/usr/bin/env python3
"""Generate configure-time CMake metadata from X-export closure manifests."""
from __future__ import annotations
import json, pathlib, sys
SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".m", ".mm"}
def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
def key(value: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in value.upper())
def main() -> int:
    if len(sys.argv) not in (4, 5):
        raise SystemExit("usage: generate_mirror_units.py MIRROR_ROOT CLOSURE_DIR OUTPUT [BUILD_INPUT_ROOT]")
    # Closure paths under build-rehearsal/ name the exporting build tree
    # (third-party copies, generated headers and sources). The mirror does not
    # carry them; an explicit build-input root supplies them as declared
    # build-machine inputs, never silently.
    build_input_root = pathlib.Path(sys.argv[4]).resolve() if len(sys.argv) == 5 and sys.argv[4] else None
    def resolve(rel: pathlib.Path):
        if (mirror_root / rel).exists():
            return mirror_root / rel
        if build_input_root is not None and rel.parts and rel.parts[0] == "build-rehearsal":
            candidate = build_input_root / pathlib.Path(*rel.parts[1:])
            if candidate.exists():
                return candidate
        return None
    mirror_root = pathlib.Path(sys.argv[1]).resolve()
    closure_dir = pathlib.Path(sys.argv[2]).resolve()
    output = pathlib.Path(sys.argv[3])
    manifests = sorted(closure_dir.glob("*.json"))
    if not manifests:
        raise SystemExit(f"no closure manifests in {closure_dir}")
    units = []
    for manifest_path in manifests:
        data = json.loads(manifest_path.read_text())
        unit, unit_key, target_rows = manifest_path.stem, key(manifest_path.stem), []
        for target in data.get("targets", []):
            target_name = target.get("name", "")
            if not target_name:
                raise SystemExit(f"target without name in {manifest_path}")
            target_key, sources = key(f"{unit}_{target_name}"), []
            for source in target.get("sources", []):
                source_path = pathlib.Path(source)
                if source_path.is_absolute():
                    # Third-party sources a Pulp target compiles in place (woff2
                    # from the FetchContent cache). Declared build-machine inputs.
                    if source_path.exists() and source_path.suffix in SOURCE_SUFFIXES:
                        sources.append(str(source_path))
                    continue
                candidate = resolve(source_path)
                if candidate is not None and candidate.suffix in SOURCE_SUFFIXES:
                    sources.append(str(candidate))
            target_rows.append((target_name, target_key, sources, target))
        units.append((unit, unit_key, target_rows))
    lines = ["# GENERATED by tools/packaging/generate_mirror_units.py; do not edit.", "set(VELLUM_MIRROR_UNITS"]
    lines += [f"  {quote(unit)}" for unit, _, _ in units] + [")", "set(VELLUM_MIRROR_REHEARSAL_TARGETS)"]
    for unit, unit_key, targets in units:
        lines.append(f"set(VELLUM_MIRROR_UNIT_{unit_key}_TARGETS)")
        for target_name, target_key, sources, target in targets:
            lines.append(f"list(APPEND VELLUM_MIRROR_UNIT_{unit_key}_TARGETS {quote(target_name)})")
            lines.append(f"list(APPEND VELLUM_MIRROR_REHEARSAL_TARGETS {quote(f"{unit}|{target_name}")})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_SOURCES")
            lines += [f"  {quote(source)}" for source in sources] + [")"]
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_INCLUDE_DIRS)")
            for include_dir in target.get("include_dirs", []):
                path = pathlib.Path(include_dir)
                if path.is_absolute():
                    if path.is_dir():
                        lines.append(f"list(APPEND VELLUM_MIRROR_TARGET_{target_key}_INCLUDE_DIRS {quote(str(path))})")
                elif (resolved := resolve(path)) is not None and resolved.is_dir():
                    lines.append(f"list(APPEND VELLUM_MIRROR_TARGET_{target_key}_INCLUDE_DIRS {quote(str(resolved))})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_DEFINITIONS)")
            for definition in target.get("compile_definitions", []):
                lines.append(f"list(APPEND VELLUM_MIRROR_TARGET_{target_key}_DEFINITIONS {quote(definition)})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_LINK_TARGETS)")
            for dependency in target.get("link_targets", []):
                lines.append(f"list(APPEND VELLUM_MIRROR_TARGET_{target_key}_LINK_TARGETS {quote(dependency)})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_UNIT {quote(unit)})")
            lines.append(f"set(VELLUM_MIRROR_TARGET_{target_key}_NAME {quote(target_name)})")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
    return 0
if __name__ == "__main__":
    raise SystemExit(main())
