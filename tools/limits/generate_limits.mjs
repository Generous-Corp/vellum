import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const HEADER = resolve(root, 'graphics/include/vellum/graphics/limits.hpp');
const OUTPUTS = [
    resolve(root, 'packages/vellum-design-ir/src/limits.generated.js'),
    resolve(root, 'packages/vellum-ui/src/limits.generated.js'),
];
const BEGIN = '// vellum-limits-begin';
const END = '// vellum-limits-end';
const DECLARATION =
    /^inline constexpr (?:std::)?(?:uint32_t|uint64_t|int32_t|size_t|float|double) (k[A-Za-z0-9]+) = ([0-9]+(?:\.[0-9]+)?(?:[eE][-+]?[0-9]+)?)(?:[UuFf]|ULL)?;$/;

export function parseHeader(text) {
    const start = text.indexOf(BEGIN);
    const end = text.indexOf(END);
    if (start < 0 || end < start) throw new Error('limits.hpp is missing its begin or end marker');
    const limits = [];
    const seen = new Set();
    for (const raw of text.slice(start + BEGIN.length, end).split('\n')) {
        const line = raw.trim();
        if (line === '' || line.startsWith('///')) continue;
        const match = DECLARATION.exec(line);
        if (!match) throw new Error(`cannot parse limits.hpp line: ${line}`);
        const name = match[1].slice(1).replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
        if (seen.has(name)) throw new Error(`duplicate limit ${name}`);
        seen.add(name);
        const value = Number(match[2]);
        if (!Number.isFinite(value)) throw new Error(`limit ${name} is not finite`);
        limits.push([name, value]);
    }
    if (limits.length === 0) throw new Error('limits.hpp declares no limits');
    return limits;
}

export function render(limits) {
    const lines = ['// Generated by tools/limits/generate_limits.mjs from graphics/include/vellum/graphics/limits.hpp. Do not edit.'];
    for (const [name, value] of limits) lines.push(`export const ${name} = ${value};`);
    return `${lines.join('\n')}\n`;
}

export function expectedOutputs() {
    const text = render(parseHeader(readFileSync(HEADER, 'utf8')));
    return OUTPUTS.map((path) => [path, text]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const check = process.argv.includes('--check');
    let drift = false;
    for (const [path, text] of expectedOutputs()) {
        if (check) {
            let current = null;
            try { current = readFileSync(path, 'utf8'); } catch { current = null; }
            if (current !== text) {
                drift = true;
                process.stderr.write(`limits drift: ${path} does not match limits.hpp; run node tools/limits/generate_limits.mjs\n`);
            }
        } else {
            writeFileSync(path, text);
        }
    }
    process.exit(drift ? 1 : 0);
}
