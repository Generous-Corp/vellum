import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BEGIN = '// vellum-limits-begin';
const END = '// vellum-limits-end';
const DECLARATION =
    /^inline constexpr (?:std::)?(?:uint32_t|uint64_t|int32_t|size_t|float|double) (k[A-Za-z0-9]+) = ([0-9]+(?:\.[0-9]+)?(?:[eE][-+]?[0-9]+)?)(?:[UuFf]|ULL)?;$/;

export function parseHeader(text) {
    const start = text.indexOf(BEGIN);
    const end = text.indexOf(END);
    if (start < 0 || end < start) throw new Error('the limits header is missing its begin or end marker');
    const limits = [];
    const seen = new Set();
    for (const raw of text.slice(start + BEGIN.length, end).split('\n')) {
        const line = raw.trim();
        if (line === '' || line.startsWith('///')) continue;
        const match = DECLARATION.exec(line);
        if (!match) throw new Error(`cannot parse limits header line: ${line}`);
        const name = match[1].slice(1).replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
        if (seen.has(name)) throw new Error(`duplicate limit ${name}`);
        seen.add(name);
        const value = Number(match[2]);
        if (!Number.isFinite(value)) throw new Error(`limit ${name} is not finite`);
        limits.push([name, value]);
    }
    if (limits.length === 0) throw new Error('the limits header declares no limits');
    return limits;
}

export function render(limits, label) {
    const lines = [`// Generated by tools/limits/generate_limits.mjs from ${label}. Do not edit.`];
    for (const [name, value] of limits) lines.push(`export const ${name} = ${value};`);
    return `${lines.join('\n')}\n`;
}

export function expectedOutput(headerPath, label) {
    return render(parseHeader(readFileSync(headerPath, 'utf8')), label);
}

export function parseArguments(argv) {
    const options = { header: null, label: null, outputs: [], check: false };
    for (let i = 0; i < argv.length; i += 1) {
        const argument = argv[i];
        if (argument === '--check') options.check = true;
        else if (argument === '--header') options.header = argv[++i];
        else if (argument === '--label') options.label = argv[++i];
        else if (argument === '--out') options.outputs.push(argv[++i]);
        else throw new Error(`unknown argument ${argument}`);
    }
    if (!options.header || options.outputs.length === 0 || options.outputs.some((path) => !path)) {
        throw new Error('usage: generate_limits.mjs --header <header> --out <file> [--out <file>...] [--label <text>] [--check]');
    }
    options.label ??= options.header;
    return options;
}

export function run(argv) {
    const options = parseArguments(argv);
    const text = expectedOutput(options.header, options.label);
    let drift = false;
    for (const path of options.outputs) {
        if (options.check) {
            let current = null;
            try { current = readFileSync(path, 'utf8'); } catch { current = null; }
            if (current !== text) {
                drift = true;
                process.stderr.write(`limits drift: ${path} does not match ${options.header}\n`);
            }
        } else {
            writeFileSync(path, text);
        }
    }
    return drift ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    try {
        process.exit(run(process.argv.slice(2)));
    } catch (error) {
        process.stderr.write(`${error.message}\n`);
        process.exit(2);
    }
}
