// Lock-to-source tests for hand-authored JSX/TSX patching.
//
// These tests prove the lock-to-source contract:
//   tweak (anchor_id → property_path → value)
//     → jsx_lock_tweak_into_source
//     → the authored JSX/TSX now carries the new value at the right span
//     → every other byte (prose, comments, formatting) is preserved.
//
// Scope is Path B only, *hand-authored* JSX/TSX, located by the
// `data-pulp-anchor` instrumentation attribute. Path A (generated
// web-compat JS) and Path C (DESIGN.md tokens) are out of scope here.

#include "framework_test.hpp"

#include <vellum/view/jsx_lock.hpp>

#include <string>

using namespace vellum::view;

// A failed precondition ends the case, since later checks read what it guards.
#define REQUIRE(expression)                                                    \
    do {                                                                       \
        if (!(expression)) {                                                   \
            ::framework_test::record_failure(#expression, __FILE__, __LINE__); \
            return;                                                            \
        }                                                                      \
    } while (false)

namespace {

// A small hand-authored TSX panel with two instrumented elements: a
// frame with an inline style object, and a Knob with bare-attribute and
// expression-container props.
const char* kPanelTsx = R"TSX(// MyPanel.tsx, hand-authored instrument UI.
// The padding here was tuned by hand; keep this comment.
import { Knob, Frame } from '@example/ui';

export const MyPanel = () => (
  <Frame
    data-pulp-anchor="sha1:frame-root"
    style={{ padding: 8, background: '#222222', gap: 4 }}
  >
    <Knob
      data-pulp-anchor="sha1:knob-gain"
      label="Gain"
      width={80}
      color="#888888"
      style={{ borderRadius: 4, opacity: 1 }}
    />
  </Frame>
);
)TSX";

}  // namespace

// ── Property-path mapping ───────────────────────────────────────────────

FRAMEWORK_TEST(jsx_lock_property_to_key_maps_dotted_paths) {
    REQUIRE(jsx_lock_property_to_key("paint.backgroundColor") == "backgroundColor");
    REQUIRE(jsx_lock_property_to_key("style.width") == "width");
    REQUIRE(jsx_lock_property_to_key("layout.padding") == "padding");
    REQUIRE(jsx_lock_property_to_key("paint.background-color") == "backgroundColor");
    REQUIRE(jsx_lock_property_to_key("layout.padding_top") == "paddingTop");
    REQUIRE(jsx_lock_property_to_key("width") == "width");

    {
        REQUIRE(!jsx_lock_property_to_key("audio.gain").has_value());
        REQUIRE(!jsx_lock_property_to_key("paint.unicornHorn").has_value());
        REQUIRE(!jsx_lock_property_to_key("layout.padding.top").has_value());
        REQUIRE(!jsx_lock_property_to_key("   ").has_value());
    }
}

// ── Authored-vs-generated detection ─────────────────────────────────────

FRAMEWORK_TEST(is_authored_jsx_source_distinguishes_authored_jsx_from_generated) {
    REQUIRE(is_authored_jsx_source(kPanelTsx));
    REQUIRE(is_authored_jsx_source("export const A = () => <div/>;\n"));

    {
        REQUIRE(!is_authored_jsx_source(
            "// Generated by Pulp import-design from panel.fig\n"
            "const x = document.createElement('div');\n"));
        REQUIRE(!is_authored_jsx_source(
            "// @generated\n<div/>\n"));
    }
    {
        REQUIRE(!is_authored_jsx_source("const x = 1;\nconst y = 2;\n"));
    }
}

// ── Patch a property inside an inline style object ──────────────────────

FRAMEWORK_TEST(jsx_lock_patches_a_style_object_property_by_anchor) {
    JsxLockTweak tweak{"sha1:frame-root", "layout.padding", "16"};
    JsxLockResult r = jsx_lock_tweak_into_source(kPanelTsx, tweak);

    REQUIRE(r.status == JsxLockStatus::patched);
    REQUIRE(r.ok());
    REQUIRE(r.mutated());
    REQUIRE(r.property == "padding");
    REQUIRE(r.line > 0);
    // The numeric literal was rewritten in place; the unit-less number
    // stays a bare JS number.
    REQUIRE(r.source.find("padding: 16,") != std::string::npos);
    REQUIRE(r.source.find("padding: 8,") == std::string::npos);
    // Sibling properties are untouched.
    REQUIRE(r.source.find("background: '#222222'") != std::string::npos);
    REQUIRE(r.source.find("gap: 4") != std::string::npos);
}

FRAMEWORK_TEST(jsx_lock_patches_a_quoted_style_object_string_value) {
    JsxLockTweak tweak{"sha1:frame-root", "paint.background", "#5a5a5a"};
    JsxLockResult r = jsx_lock_tweak_into_source(kPanelTsx, tweak);

    REQUIRE(r.status == JsxLockStatus::patched);
    REQUIRE(r.source.find("background: '#5a5a5a'") != std::string::npos);
    REQUIRE(r.source.find("'#222222'") == std::string::npos);
}

