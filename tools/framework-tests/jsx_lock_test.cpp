// ── Value escaping (a value with a quote must not break the JSX) ────────

FRAMEWORK_TEST(jsx_lock_escapes_single_quotes_in_a_string_value) {
    const std::string src =
        "<Frame data-pulp-anchor=\"a\" style={{ fontFamily: 'Inter' }}/>\n";
    JsxLockResult r = jsx_lock_tweak_into_source(
        src, {"a", "paint.fontFamily", "Mike's Font"});

    REQUIRE(r.status == JsxLockStatus::patched);
    REQUIRE(r.source.find("Mike\\'s Font") != std::string::npos);
}

FRAMEWORK_TEST(jsx_lock_escapes_double_quotes_in_double_quoted_values) {
    const std::string style_src =
        "<Frame data-pulp-anchor=\"a\" style={{ fontFamily: \"Inter\" }}/>\n";
    JsxLockResult style = jsx_lock_tweak_into_source(
        style_src, {"a", "paint.fontFamily", "Quote \" Font"});

    REQUIRE(style.status == JsxLockStatus::patched);
    REQUIRE(style.source.find("fontFamily: \"Quote \\\" Font\"") !=
            std::string::npos);

    const std::string attr_src =
        "<Knob data-pulp-anchor=\"a\" color=\"old\"/>\n";
    JsxLockResult attr = jsx_lock_tweak_into_source(
        attr_src, {"a", "paint.color", "he said \"blue\""});

    REQUIRE(attr.status == JsxLockStatus::patched);
    REQUIRE(attr.source.find("color=\"he said \\\"blue\\\"\"") !=
            std::string::npos);
}

FRAMEWORK_TEST(jsx_lock_escapes_js_control_characters_in_string_values) {
    const std::string src =
        "<Frame data-pulp-anchor=\"a\" style={{ fontFamily: 'Inter' }}/>\n";
    std::string value = "Line\nTab\tCarriage\r";
    value.push_back(static_cast<char>(0x1F));
    value += "Slash\\Quote'";

    JsxLockResult r = jsx_lock_tweak_into_source(
        src, {"a", "paint.fontFamily", value});

    REQUIRE(r.status == JsxLockStatus::patched);
    REQUIRE(r.source.find(
        "fontFamily: 'Line\\nTab\\tCarriage\\r\\x1FSlash\\\\Quote\\''") !=
        std::string::npos);
    REQUIRE(r.source.find("Line\nTab") == std::string::npos);
}

FRAMEWORK_TEST(jsx_lock_converts_a_numeric_prop_to_a_quoted_string_when_needed) {
    // width={80} (bare number) tweaked to a unit-bearing CSS value must
    // become a quoted string so the JS stays valid.
    const std::string src =
        "<Knob data-pulp-anchor=\"a\" width={80}/>\n";
    JsxLockResult r = jsx_lock_tweak_into_source(
        src, {"a", "style.width", "120px"});

    REQUIRE(r.status == JsxLockStatus::patched);
    REQUIRE(r.source.find("width={'120px'}") != std::string::npos);
}

// ── Multi-tweak pass ────────────────────────────────────────────────────

FRAMEWORK_TEST(jsx_lock_tweaks_into_source_applies_several_tweaks_in_one_pass) {
    std::vector<JsxLockTweak> tweaks{
        {"sha1:frame-root", "layout.padding", "16"},
        {"sha1:knob-gain", "paint.color", "#5a5a5a"},
        {"sha1:knob-gain", "style.width", "120"},
    };
    auto results = jsx_lock_tweaks_into_source(kPanelTsx, tweaks);

    REQUIRE(results.size() == 3);
    for (const auto& r : results) REQUIRE(r.status == JsxLockStatus::patched);

    const std::string& final = results.back().source;
    for (const auto& r : results) REQUIRE(r.source == final);
    REQUIRE(final.find("padding: 16,") != std::string::npos);
    REQUIRE(final.find("color=\"#5a5a5a\"") != std::string::npos);
    REQUIRE(final.find("width={120}") != std::string::npos);
}

