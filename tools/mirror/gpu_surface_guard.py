#!/usr/bin/env python3
"""Keep the GPU device types off the installed mirror's supported surface.

After Pulp's GPU device layer forwards to Vellum's gpu-runtime,
`pulp::render::GpuSurface` and `GpuCompute` are `gpu_runtime` types whose
symbols the installed package does not export. Installed consumers may not
use them, or any mirrored header that exposes them.

The mirror itself stays overlay-free: every file under `mirror/` equals Pulp's.
Only the *installed* copy of each choke header changes. A choke header is one
that declares the `gpu_runtime` types or includes `<gpu_runtime/...>`. Its
installed copy gains one line after `#pragma once` that includes
`vellum/mirror/gpu_surface_unsupported.hpp`. That config header is an
`#error` unless `VELLUM_MIRROR_BUILD` is defined, which only VellumMirror.cmake
sets, privately, on the mirror's own targets. Every header that exposes the
types reaches a choke header, so guarding the choke headers guards them all.

The choke set is computed from the mirrored headers, never listed by hand, so
a choke header a later export adds is guarded too.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

MIRROR_DIR = "mirror"
# After the M2 8b transfer (Decision 0010 option a) the renamed units live in
# framework/, with the export's layout below it.
FRAMEWORK_DIR = "framework"


def units_dir(repo: Path) -> str:
    """The source root of the packaged units: framework/ once transferred, mirror/ before."""
    return FRAMEWORK_DIR if (repo / FRAMEWORK_DIR).is_dir() else MIRROR_DIR
INCLUDE_ROOT_GLOB = "core/*/include"
HEADER_SUFFIXES = frozenset({".h", ".hh", ".hpp", ".hxx", ".inc", ".inl", ".ipp"})
CONFIG_RELATIVE = "vellum/mirror/gpu_surface_unsupported.hpp"
GUARD_LINE = f"#include <{CONFIG_RELATIVE}>"
UNSUPPORTED_MESSAGE = "not part of the installed mirror's supported surface"
CONFIG_HEADER = f"""\
// GENERATED by tools/mirror/gpu_surface_guard.py; installed with the mirror only.
#pragma once
#if !defined(VELLUM_MIRROR_BUILD)
#error "Vellum mirror: vellum::render::GpuSurface / GpuCompute and the mirrored headers that expose them (for example <vellum/view/window_host.hpp>) are {UNSUPPORTED_MESSAGE}. See docs/cli/install-artifact.md, Unsupported surface."
#endif
"""
CHOKE_MARKER = re.compile(
    r"^\s*#\s*include\s*[<\"]gpu_runtime/|\bnamespace\s+gpu_runtime\b", re.MULTILINE)
PRAGMA_ONCE = re.compile(r"^[ \t]*#[ \t]*pragma[ \t]+once[ \t]*\r?\n", re.MULTILINE)


class GuardError(RuntimeError):
    """A choke header cannot be guarded, or an installed header is not what it must be."""


def include_roots(repo: Path) -> list[Path]:
    """The mirror's public include roots, the directories the install copies."""
    return sorted(p for p in (repo / units_dir(repo)).glob(INCLUDE_ROOT_GLOB) if p.is_dir())


def is_choke_header(text: str) -> bool:
    return CHOKE_MARKER.search(text) is not None


def choke_headers(repo: Path) -> list[tuple[Path, str]]:
    """Every (include root, header path relative to it) that must be guarded."""
    found = []
    for root in include_roots(repo):
        for path in sorted(root.rglob("*")):
            if path.is_file() and path.suffix in HEADER_SUFFIXES:
                if is_choke_header(path.read_text(encoding="utf-8", errors="replace")):
                    found.append((root, path.relative_to(root).as_posix()))
    return found


def guarded_text(text: str, where: str) -> str:
    """The installed copy of a choke header: the guard line right after `#pragma once`."""
    match = PRAGMA_ONCE.search(text)
    if match is None:
        raise GuardError(f"{where}: a choke header needs #pragma once to carry the guard")
    return text[:match.end()] + GUARD_LINE + "\n" + text[match.end():]


def write_guard(repo: Path, out_dir: Path) -> dict:
    """Write the guarded copies and the config header; return what the install needs."""
    headers = []
    for root, relative in choke_headers(repo):
        source = root / relative
        copy = out_dir / "headers" / root.relative_to(repo).as_posix() / relative
        copy.parent.mkdir(parents=True, exist_ok=True)
        copy.write_text(guarded_text(source.read_text(encoding="utf-8"), str(source)), encoding="utf-8")
        headers.append({"include_dir": str(root), "relative": relative, "copy": str(copy)})
    config_dir = out_dir / "config"
    config = config_dir / CONFIG_RELATIVE
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text(CONFIG_HEADER, encoding="utf-8")
    manifest = out_dir / "gpu-guarded-headers.txt"
    manifest.write_text("".join(f"{h['relative']}\n" for h in headers), encoding="utf-8")
    return {"config_dir": str(config_dir), "manifest": str(manifest), "headers": headers}


def check_installed(include_dir: Path, repo: Path, require_guard: bool) -> list[str]:
    """Problems with an installed mirror include tree, compared with the landed mirror.

    Each installed header that a mirror include root also holds must equal its
    source byte for byte, unless it is a choke header, whose installed copy
    must equal the source with exactly the guard line inserted.
    """
    problems = []
    sources: dict[str, Path] = {}
    for root in include_roots(repo):
        for path in root.rglob("*"):
            if path.is_file():
                sources.setdefault(path.relative_to(root).as_posix(), path)
    guarded = 0
    for relative, source in sorted(sources.items()):
        installed = include_dir / relative
        if not installed.is_file():
            continue
        expected = source.read_text(encoding="utf-8", errors="replace")
        if source.suffix in HEADER_SUFFIXES and is_choke_header(expected):
            guarded += 1
            try:
                expected = guarded_text(expected, str(source))
            except GuardError as error:
                problems.append(str(error))
                continue
        if installed.read_text(encoding="utf-8", errors="replace") != expected:
            problems.append(f"installed {relative} is not its mirror source"
                            + (" with the guard line" if expected.find(GUARD_LINE) >= 0 else ""))
    config = include_dir / CONFIG_RELATIVE
    if guarded:
        if not config.is_file() or config.read_text(encoding="utf-8") != CONFIG_HEADER:
            problems.append(f"installed {CONFIG_RELATIVE} is missing or not the generated config header")
    elif require_guard:
        problems.append("no installed choke header was found, but the guard is required")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("check", help="compare an installed mirror include tree with the landed mirror")
    check.add_argument("--include-dir", type=Path, required=True)
    check.add_argument("--repo", type=Path, required=True)
    check.add_argument("--require-guard", action="store_true")
    args = parser.parse_args(argv)
    problems = check_installed(args.include_dir, args.repo, args.require_guard)
    for problem in problems:
        print(f"gpu surface guard: {problem}", file=sys.stderr)
    if not problems:
        print("gpu surface guard: installed headers match the mirror (choke headers guarded)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
