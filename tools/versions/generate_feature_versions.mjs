import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const HEADER = resolve(root, 'graphics/include/vellum/graphics/feature_versions.hpp');
const SCENE_HEADER = resolve(root, 'graphics/include/vellum/graphics/scene.hpp');
const OUTPUTS = [
    resolve(root, 'packages/vellum-design-ir/src/feature-versions.generated.js'),
    resolve(root, 'packages/vellum-ui/src/feature-versions.generated.js'),
];
const BEGIN = '// vellum-feature-versions-begin';
const END = '// vellum-feature-versions-end';
const ROW = /^FeatureVersion\{"([a-z][a-z-]*)", ([0-9]+)U, ([0-9]+)U\},$/;

function contiguousFrom(versions, first, what) {
    const sorted = [...versions].sort((a, b) => a - b);
    sorted.forEach((version, index) => {
        if (version !== first + index) {
            throw new Error(`${what} versions must count up from ${first} without gaps or repeats: ${sorted.join(', ')}`);
        }
    });
}

export function parseTable(text) {
    const start = text.indexOf(BEGIN);
    const end = text.indexOf(END);
    if (start < 0 || end < start) throw new Error('feature_versions.hpp is missing its begin or end marker');
    const rows = [];
    for (const raw of text.slice(start + BEGIN.length, end).split('\n')) {
        const line = raw.trim();
        if (line === '') continue;
        const match = ROW.exec(line);
        if (!match) throw new Error(`cannot parse feature_versions.hpp line: ${line}`);
        rows.push({ name: match[1], sceneVersion: Number(match[2]), designIrVersion: Number(match[3]) });
    }
    if (rows.length === 0) throw new Error('feature_versions.hpp declares no rows');
    const names = rows.map((row) => row.name);
    if (new Set(names).size !== names.length) throw new Error('feature names must be unique');
    for (const row of rows) {
        if (row.sceneVersion === 0 && row.designIrVersion === 0) {
            throw new Error(`feature ${row.name} has neither a scene nor a DesignIR version`);
        }
    }
    contiguousFrom(rows.map((row) => row.sceneVersion).filter(Boolean), 2, 'scene');
    contiguousFrom(rows.map((row) => row.designIrVersion).filter(Boolean), 2, 'DesignIR');
    return rows;
}

export function claimedSceneVersions(sceneText) {
    const start = sceneText.indexOf('Claimed versions, in order:');
    const end = sceneText.indexOf('inline constexpr std::uint32_t kSceneVersion', start);
    if (start < 0 || end < start) throw new Error('scene.hpp has no claimed-version list before kSceneVersion');
    const flat = sceneText.slice(start, end).replace(/^\s*\/\/\/ ?/gm, ' ').replace(/\s+/g, ' ');
    return [...flat.matchAll(/version (\d+):/g)].map((match) => Number(match[1]));
}

export function claimedListProblems(rows, sceneText) {
    const expected = rows.map((row) => row.sceneVersion).filter(Boolean).sort((a, b) => a - b);
    const claimed = claimedSceneVersions(sceneText);
    return JSON.stringify(claimed) === JSON.stringify(expected)
        ? []
        : [`the claimed-version list in scene.hpp names versions ${claimed.join(', ')}; the table has ${expected.join(', ')}`];
}

function schemaVersions(rows) {
    const later = rows.map((row) => row.designIrVersion).filter(Boolean).sort((a, b) => a - b);
    return [1, ...later];
}

export function render(rows) {
    const lines = [
        '// Generated by tools/versions/generate_feature_versions.mjs from graphics/include/vellum/graphics/feature_versions.hpp. Do not edit.',
        'export const FEATURE_VERSIONS = Object.freeze([',
        ...rows.map((row) => `    Object.freeze({ name: '${row.name}', sceneVersion: ${row.sceneVersion}, designIrVersion: ${row.designIrVersion} }),`),
        ']);',
        '',
        `export const DESIGN_IR_SCHEMA_VERSIONS = Object.freeze([${schemaVersions(rows).join(', ')}]);`,
        '',
        'function row(name) {',
        '    const found = FEATURE_VERSIONS.find((feature) => feature.name === name);',
        '    if (!found) throw new Error(`unknown feature ${name}`);',
        '    return found;',
        '}',
        '',
        'export function sceneVersionOf(name) {',
        '    return row(name).sceneVersion;',
        '}',
        '',
        'export function designIrVersionOf(name) {',
        '    return row(name).designIrVersion;',
        '}',
        '',
    ];
    return lines.join('\n');
}

export function expectedOutputs() {
    const text = render(parseTable(readFileSync(HEADER, 'utf8')));
    return OUTPUTS.map((path) => [path, text]);
}

export function sourcePaths() {
    return { header: HEADER, sceneHeader: SCENE_HEADER };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const check = process.argv.includes('--check');
    let failed = false;
    const rows = parseTable(readFileSync(HEADER, 'utf8'));
    if (check) {
        for (const problem of claimedListProblems(rows, readFileSync(SCENE_HEADER, 'utf8'))) {
            failed = true;
            process.stderr.write(`${problem}\n`);
        }
    }
    for (const [path, text] of expectedOutputs()) {
        if (check) {
            let current = null;
            try { current = readFileSync(path, 'utf8'); } catch { current = null; }
            if (current !== text) {
                failed = true;
                process.stderr.write(`feature versions drift: ${path} does not match feature_versions.hpp; run node tools/versions/generate_feature_versions.mjs\n`);
            }
        } else {
            writeFileSync(path, text);
        }
    }
    process.exit(failed ? 1 : 0);
}
